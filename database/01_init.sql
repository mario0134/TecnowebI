CREATE TABLE IF NOT EXISTS lineas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  zona VARCHAR(80) NOT NULL,
  descripcion TEXT NOT NULL,
  color VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS micros (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa VARCHAR(20) NOT NULL UNIQUE,
  interno VARCHAR(20) NOT NULL UNIQUE,
  capacidad INTEGER NOT NULL CHECK (capacidad BETWEEN 1 AND 100),
  ocupacion_actual INTEGER NOT NULL DEFAULT 0 CHECK (ocupacion_actual >= 0),
  estado VARCHAR(20) NOT NULL CHECK (estado IN ('ACTIVO', 'MANTENIMIENTO', 'INACTIVO')),
  incidencia_motivo TEXT,
  linea_id INTEGER NOT NULL REFERENCES lineas(id)
);

CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL DEFAULT 'ADMIN' CHECK (rol = 'ADMIN')
);

CREATE TABLE IF NOT EXISTS tarifas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria VARCHAR(30) NOT NULL UNIQUE,
  descripcion VARCHAR(120) NOT NULL,
  monto NUMERIC(10, 2) NOT NULL CHECK (monto > 0)
);

CREATE TABLE IF NOT EXISTS viajes_comprobantes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_comprobante VARCHAR(40) NOT NULL UNIQUE,
  micro_id INTEGER NOT NULL REFERENCES micros(id),
  categoria_pasajero VARCHAR(30) NOT NULL REFERENCES tarifas(categoria),
  tarifa_aplicada NUMERIC(10, 2) NOT NULL CHECK (tarifa_aplicada > 0),
  estado_viaje VARCHAR(20) NOT NULL DEFAULT 'ACTIVO' CHECK (estado_viaje IN ('ACTIVO', 'TRASBORDADO')),
  creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

